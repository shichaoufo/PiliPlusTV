///
/// 0 = 焦点在播放器（播放器热键生效）
/// 1 = 侧栏最外层（Tab 栏一排：标签页/发弹幕/弹幕开关）
/// 2 = 侧栏内容（评论列表 / 相关视频 / 播放列表）
/// 3 = 评论详情弹窗（由详情页设置/恢复）
/// 4 = 评论详情内某条评论的内部停靠点（正文/回复/点赞等，由详情页设置）
///
/// 注意：≥3 由评论详情页自行管理（打开时置位、关闭时恢复），视频页的
/// 返回键处理见到 ≥3 一律不参与，避免把焦点从详情页抢走。
/// 0/1/2 之间**不再依赖该计数分发返回键**——视频页按焦点实际所在位置
/// （`_sideRowFocusNode.hasFocus`）判断：在最外层一排 → 交还播放器；
/// 在侧栏内容 → 回 Tab 栏。计数只保留给详情页做打开/关闭的标记。
